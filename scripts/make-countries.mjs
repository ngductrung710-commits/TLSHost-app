// Regenerates src/lib/countries.ts from the ICU data Node already ships.
//
//   node scripts/make-countries.mjs
//
// Typing 250 country names in two languages by hand is 500 chances to
// misspell one, and Intl knows them all. The output is committed rather than
// computed at runtime: the wizard's <select> is server-rendered and then
// hydrated, so the two sides must agree on every option, and Node's ICU and
// the browser's are not guaranteed to be the same build.

import { writeFileSync } from "node:fs";

// Codes ICU knows that are not countries: macro-regions and the EU/UN.
const NOT_A_COUNTRY = new Set(["EU", "EZ", "UN", "QO", "XA", "XB", "XK"]);

const vi = new Intl.DisplayNames(["vi"], { type: "region", fallback: "none" });
const en = new Intl.DisplayNames(["en"], { type: "region", fallback: "none" });

const LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("");
const rows = [];
for (const a of LETTERS) {
  for (const b of LETTERS) {
    const code = a + b;
    if (NOT_A_COUNTRY.has(code)) continue;
    const nameVi = vi.of(code);
    const nameEn = en.of(code);
    if (!nameVi || !nameEn || nameVi === code) continue;
    rows.push({ code, vi: nameVi, en: nameEn });
  }
}

// Sorted the way a Vietnamese reader scans a list, which is not code order.
rows.sort((x, y) => x.vi.localeCompare(y.vi, "vi"));

const body = rows
  .map((r) => `  { code: ${JSON.stringify(r.code)}, vi: ${JSON.stringify(r.vi)}, en: ${JSON.stringify(r.en)} },`)
  .join("\n");

const file = `// Generated by scripts/make-countries.mjs — do not edit by hand.
//
// ISO 3166-1 alpha-2, with the name in both languages. Names live here rather
// than in src/i18n/en.ts because they are data, not copy: a dictionary keyed by
// Vietnamese sentences is the right home for "Đặt tên cho chỗ nghỉ." and the
// wrong home for 250 proper nouns that no one will ever rewrite.

export type Country = { code: string; vi: string; en: string };

export const COUNTRIES: readonly Country[] = [
${body}
];

const BY_CODE = new Map(COUNTRIES.map((c) => [c.code, c]));

/** The country's name in the reader's language, or the raw code if unknown. */
export function countryName(code: string | null | undefined, lang: "vi" | "en"): string {
  if (!code) return "";
  return BY_CODE.get(code)?.[lang] ?? code;
}

export function isCountryCode(code: string): boolean {
  return BY_CODE.has(code);
}
`;

writeFileSync("src/lib/countries.ts", file);
console.log(`wrote src/lib/countries.ts with ${rows.length} countries`);
